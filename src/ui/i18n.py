DEFAULT_LANGUAGE = "zh_CN"
SUPPORTED_LANGUAGES = ("zh_CN", "en_US")
LANGUAGE_LABELS = {
    "zh_CN": "中文",
    "en_US": "English",
}

_language = DEFAULT_LANGUAGE


def normalize_language(language: str | None) -> str:
    value = str(language or "").strip().replace("-", "_")
    aliases = {
        "zh": "zh_CN",
        "zh_CN": "zh_CN",
        "zh_Hans": "zh_CN",
        "Chinese": "zh_CN",
        "中文": "zh_CN",
        "en": "en_US",
        "en_US": "en_US",
        "English": "en_US",
    }
    return aliases.get(value, DEFAULT_LANGUAGE)


def set_language(language: str | None) -> str:
    global _language
    _language = normalize_language(language)
    return _language


def current_language() -> str:
    return _language


def language_label(language: str | None = None) -> str:
    code = normalize_language(language or _language)
    return LANGUAGE_LABELS.get(code, code)


def tr(key: str, **kwargs: Any) -> str:
    table = _TRANSLATIONS.get(_language, {})
    template = table.get(key)
    if template is None:
        template = _TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    if kwargs:
        try:
            return template.format(**kwargs)
        except Exception:
            return template
    return template


